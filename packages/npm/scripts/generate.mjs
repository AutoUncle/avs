// Generates src/types.ts from src/avs.schema.json (copied in by /scripts/sync).
import { readFile, writeFile } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";

const schema = JSON.parse(await readFile(new URL("../src/avs.schema.json", import.meta.url), "utf8"));

// The root type is named by the second argument, not the schema's title or $id.
delete schema.title;
delete schema.$id;

// A $ref with sibling keywords (usually a description) makes the generator emit a
// duplicate type (CatalogueRef1, CatalogueRef2, …); keep only the $ref.
const bareRefs = (node) => {
  if (Array.isArray(node)) return node.forEach(bareRefs);
  if (!node || typeof node !== "object") return;
  if (node.$ref) for (const key of Object.keys(node)) if (key !== "$ref") delete node[key];
  Object.values(node).forEach(bareRefs);
};
bareRefs(schema);

// The generator ignores `properties` that sit beside an `allOf`, so a level such as
// identity.generation (allOf: [CatalogueRef] + code, fromYear, …) would lose its own
// fields. Move those siblings into the allOf so they come out as an intersection.
const foldAllOf = (node) => {
  if (Array.isArray(node)) return node.forEach(foldAllOf);
  if (!node || typeof node !== "object") return;
  if (Array.isArray(node.allOf) && (node.properties || node.required)) {
    const own = { type: "object", additionalProperties: false };
    for (const key of ["properties", "required"]) {
      if (node[key]) {
        own[key] = node[key];
        delete node[key];
      }
    }
    node.allOf.push(own);
  }
  Object.values(node).forEach(foldAllOf);
};
foldAllOf(schema);

const ts = await compile(schema, "AvsDocument", {
  bannerComment: "/* Generated by scripts/generate.mjs from avs.schema.json. Do not edit. */",
  additionalProperties: false,
  style: { singleQuote: false },
});
await writeFile(new URL("../src/types.ts", import.meta.url), ts);
